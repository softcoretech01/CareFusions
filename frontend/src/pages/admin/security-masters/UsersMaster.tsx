import { useState, useEffect } from 'react';
import { Pagination } from '@/components/ui/Pagination';
import { usePagination } from '@/hooks/usePagination';
import {
  Plus, Search, Filter, Download, Edit2, Trash2, AlertTriangle,
  Save, RefreshCw, Eye, EyeOff, ShieldCheck, ShieldOff, X
} from 'lucide-react';
import { motion, AnimatePresence } from 'framer-motion';
import { Button } from '../../../components/ui/Button';
import { Modal } from '../../../components/ui/Modal';
import { exportToExcel } from '../../../utils/exportToExcel';

const API_BASE = import.meta.env.VITE_API_URL as string;

interface UserRecord {
  id: number;
  userId: string;
  employee: string;
  username: string;
  role: string;
  department: string;
  hospital: string;
  branch: string;
  email: string;
  mobileNumber: string;
  forcePasswordChange: boolean;
  passwordExpiry: string;
  twoFactorAuth: boolean;
  loginAllowedFrom: string;
  loginAllowedTo: string;
  status: string;
  remarks: string;
  createdBy?: string;
  createdDate?: string;
  updatedBy?: string;
  updatedDate?: string;
}

// A role, with the permissions it carries (from the Role Master)
interface RoleOption {
  roleName: string;
  canCreateUsers: boolean;
  canAssignPermissions: boolean;
  defaultRole: boolean;
}

// UserCode is auto-generated by the backend (USR-001). password only exists in the form.
type UserForm = Omit<UserRecord, 'id' | 'userId' | 'createdBy' | 'createdDate' | 'updatedBy' | 'updatedDate'> & {
  password: string;
  confirmPassword: string;
};

const emptyData: UserForm = {
  employee: '',
  username: '',
  password: '',
  confirmPassword: '',
  role: '',
  department: '',
  hospital: '',
  branch: '',
  email: '',
  mobileNumber: '',
  forcePasswordChange: true,
  passwordExpiry: '90',
  twoFactorAuth: false,
  loginAllowedFrom: '00:00',
  loginAllowedTo: '23:59',
  status: 'Active',
  remarks: ''
};

const LIMITS = {
  employee: 150, username: 100, email: 150, mobileNumber: 20, remarks: 500,
  passwordMin: 8, passwordMax: 128, expiryMax: 3650,
};

const mapApiToRecord = (item: Record<string, unknown>): UserRecord => ({
  id:                  item.id                  as number,
  userId:              item.userId              as string,
  employee:            item.employee            as string,
  username:            item.username            as string,
  role:                item.role                as string,
  department:          (item.department          as string) ?? '',
  hospital:            (item.hospital            as string) ?? '',
  branch:              (item.branch              as string) ?? '',
  email:               item.email               as string,
  mobileNumber:        (item.mobileNumber        as string) ?? '',
  forcePasswordChange: Boolean(item.forcePasswordChange),
  passwordExpiry:      item.passwordExpiry != null ? String(item.passwordExpiry) : '90',
  twoFactorAuth:       Boolean(item.twoFactorAuth),
  loginAllowedFrom:    (item.loginAllowedFrom    as string) ?? '00:00',
  loginAllowedTo:      (item.loginAllowedTo      as string) ?? '23:59',
  status:              item.status              as string,
  remarks:             (item.remarks             as string) ?? '',
  createdBy:           (item.createdBy           as string) ?? undefined,
  createdDate:         item.createdDate ? String(item.createdDate).split('T')[0] : undefined,
  updatedBy:           (item.updatedBy           as string) ?? undefined,
  updatedDate:         item.updatedDate ? String(item.updatedDate).split('T')[0] : undefined,
});

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export const UsersMaster = () => {
  const [records, setRecords] = useState<UserRecord[]>([]);
  const [roleOptions, setRoleOptions] = useState<RoleOption[]>([]);
  const [departmentOptions, setDepartmentOptions] = useState<string[]>([]);
  const [searchTerm, setSearchTerm] = useState('');
  const [currentPage, setCurrentPage] = useState(1);
  const [itemsPerPage, setItemsPerPage] = useState(10);
  const [isLoading, setIsLoading] = useState(false);
  const [apiError, setApiError] = useState<string | null>(null);
  const [isSaving, setIsSaving] = useState(false);
  const [nextCode, setNextCode] = useState('');

  // Filter States
  const [showFilters, setShowFilters] = useState(false);
  const [filterRole, setFilterRole] = useState('');
  const [filterDepartment, setFilterDepartment] = useState('');

  // Form States
  const [isFormOpen, setIsFormOpen] = useState(false);
  const [isDeleteOpen, setIsDeleteOpen] = useState(false);
  const [selectedRecord, setSelectedRecord] = useState<UserRecord | null>(null);
  const [formData, setFormData] = useState<UserForm>(emptyData);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [showPassword, setShowPassword] = useState(false);

  // ── Fetch users ──────────────────────────────────────────────
  const fetchUsers = async () => {
    setIsLoading(true);
    setApiError(null);
    try {
      const res = await fetch(`${API_BASE}/users/`);
      if (!res.ok) throw new Error(`Server error: ${res.status}`);
      const data: Record<string, unknown>[] = await res.json();
      setRecords(data.map(mapApiToRecord));
    } catch (err: unknown) {
      setApiError(err instanceof Error ? err.message : 'Failed to load users');
    } finally {
      setIsLoading(false);
    }
  };

  // Roles + Department/Hospital/Branch come from the live masters
  const fetchLookups = async () => {
    try {
      const [rRes, dRes] = await Promise.all([
        fetch(`${API_BASE}/roles/`),
        fetch(`${API_BASE}/departments/`),
      ]);
      if (rRes.ok) {
        const roles: Record<string, unknown>[] = await rRes.json();
        setRoleOptions(
          roles
            .filter(r => r.status === 'Active')
            .map(r => ({
              roleName:             r.roleName as string,
              canCreateUsers:       Boolean(r.canCreateUsers),
              canAssignPermissions: Boolean(r.canAssignPermissions),
              defaultRole:          Boolean(r.defaultRole),
            }))
        );
      }
      if (dRes.ok) setDepartmentOptions((await dRes.json()).map((d: Record<string, unknown>) => d.departmentName as string));
    } catch { /* leave options as-is */ }
  };

  useEffect(() => { fetchUsers(); fetchLookups(); }, []);

  const fetchNextCode = async () => {
    setNextCode('');
    try {
      const res = await fetch(`${API_BASE}/users/next-code`);
      if (res.ok) setNextCode((await res.json()).userId ?? '');
    } catch { setNextCode(''); }
  };

  const selectedRolePerms = roleOptions.find(r => r.roleName === formData.role);

  const validateForm = () => {
    const newErrors: Record<string, string> = {};
    if (!formData.employee.trim()) newErrors.employee = 'Employee Name is required';
    if (!formData.username.trim()) newErrors.username = 'Username is required';
    if (!formData.role.trim()) newErrors.role = 'Role is required';
    if (!formData.email.trim()) newErrors.email = 'Email is required';
    else if (!EMAIL_RE.test(formData.email.trim())) newErrors.email = 'Enter a valid email address';

    // Password: required only on create; on edit, blank keeps the existing one.
    if (!selectedRecord || formData.password) {
      if (!formData.password) newErrors.password = 'Password is required';
      else if (formData.password.length < LIMITS.passwordMin) newErrors.password = `Password must be at least ${LIMITS.passwordMin} characters`;
      else if (formData.password.length > LIMITS.passwordMax) newErrors.password = `Password cannot exceed ${LIMITS.passwordMax} characters`;
      if (formData.password && formData.password !== formData.confirmPassword) newErrors.confirmPassword = 'Passwords do not match';
    }

    // Login window
    if (formData.loginAllowedTo <= formData.loginAllowedFrom) newErrors.loginAllowedTo = "'Allowed to' must be after 'allowed from'";

    // Password expiry
    const expiry = Number(formData.passwordExpiry || 0);
    if (expiry < 0) newErrors.passwordExpiry = 'Cannot be negative';
    else if (expiry > LIMITS.expiryMax) newErrors.passwordExpiry = `Cannot exceed ${LIMITS.expiryMax} days`;

    // Client-side hints (server is the source of truth)
    if (records.some(r => r.username.toLowerCase() === formData.username.trim().toLowerCase() && r.id !== selectedRecord?.id))
      newErrors.username = 'Username must be unique';
    if (records.some(r => r.email.toLowerCase() === formData.email.trim().toLowerCase() && r.id !== selectedRecord?.id))
      newErrors.email = 'Email must be unique';
    if (formData.status === 'Active' && records.some(r => r.employee.toLowerCase() === formData.employee.trim().toLowerCase() && r.status === 'Active' && r.id !== selectedRecord?.id))
      newErrors.employee = 'This employee already has an active user account';

    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  const handleCreateNew = () => {
    setSelectedRecord(null);
    setFormData(emptyData);
    setErrors({});
    setShowPassword(false);
    setIsFormOpen(true);
    fetchNextCode();
    fetchLookups();
  };

  const handleEdit = (record: UserRecord) => {
    setSelectedRecord(record);
    const { id, userId, createdBy, createdDate, updatedBy, updatedDate, ...rest } = record;
    setFormData({ ...rest, password: '', confirmPassword: '' });
    setErrors({});
    setShowPassword(false);
    setIsFormOpen(true);
    fetchLookups();
  };

  const handleDeleteRequest = (record: UserRecord) => {
    setSelectedRecord(record);
    setIsDeleteOpen(true);
  };

  const handleSaveForm = async () => {
    if (!validateForm()) return;
    setIsSaving(true);
    setApiError(null);
    try {
      const body: Record<string, unknown> = {
        employee:            formData.employee.trim(),
        username:            formData.username.trim(),
        role:                formData.role,
        department:          formData.department || null,
        hospital:            formData.hospital || null,
        branch:              formData.branch || null,
        email:               formData.email.trim(),
        mobileNumber:        formData.mobileNumber || null,
        forcePasswordChange: formData.forcePasswordChange,
        passwordExpiry:      formData.passwordExpiry === '' ? 90 : Number(formData.passwordExpiry),
        twoFactorAuth:       formData.twoFactorAuth,
        loginAllowedFrom:    formData.loginAllowedFrom,
        loginAllowedTo:      formData.loginAllowedTo,
        status:              formData.status,
        remarks:             formData.remarks || null,
      };

      let res: Response;
      if (selectedRecord) {
        // On edit a blank password means "keep the existing one" — omit it.
        if (formData.password) body.password = formData.password;
        res = await fetch(`${API_BASE}/users/${selectedRecord.id}`, {
          method: 'PUT',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ ...body, updatedBy: 'Admin' }),
        });
      } else {
        body.password = formData.password;
        res = await fetch(`${API_BASE}/users/`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ ...body, createdBy: 'Admin' }),
        });
      }
      if (!res.ok) {
        const data = await res.json().catch(() => null);
        let detail = `Save failed: ${res.status}`;
        if (data && typeof data.detail === 'string') detail = data.detail;
        else if (data && Array.isArray(data.detail) && data.detail[0]?.msg) detail = data.detail[0].msg;
        throw new Error(detail);
      }

      await fetchUsers();
      setIsFormOpen(false);
      setSelectedRecord(null);
    } catch (err: unknown) {
      setApiError(err instanceof Error ? err.message : 'Save failed');
    } finally {
      setIsSaving(false);
    }
  };

  const confirmDelete = async () => {
    if (!selectedRecord) return;
    setApiError(null);
    try {
      const res = await fetch(`${API_BASE}/users/${selectedRecord.id}`, { method: 'DELETE' });
      if (!res.ok) throw new Error(`Delete failed: ${res.status}`);
      await fetchUsers();
      setIsDeleteOpen(false);
      setSelectedRecord(null);
    } catch (err: unknown) {
      setApiError(err instanceof Error ? err.message : 'Delete failed');
      setIsDeleteOpen(false);
    }
  };

  const allDepartments = Array.from(new Set([...departmentOptions, ...records.map(r => r.department)].filter(Boolean))).sort();
  const allRoles = Array.from(new Set([...roleOptions.map(r => r.roleName), ...records.map(r => r.role)].filter(Boolean))).sort();


  const filteredRecords = records.filter(record => {
    const matchesSearch =
      record.employee.toLowerCase().includes(searchTerm.toLowerCase()) ||
      record.userId.toLowerCase().includes(searchTerm.toLowerCase()) ||
      record.username.toLowerCase().includes(searchTerm.toLowerCase());
    const matchesRole = !filterRole || record.role === filterRole;
    const matchesDepartment = !filterDepartment || record.department === filterDepartment;
    return matchesSearch && matchesRole && matchesDepartment;
  });

  const _totalPages = Math.max(1, Math.ceil(filteredRecords.length / itemsPerPage));
  const _page = Math.min(currentPage, _totalPages);
  const pagedRecords = filteredRecords.slice((_page - 1) * itemsPerPage, _page * itemsPerPage);

  const { page, setPage, pageSize, total, paged } = usePagination(allRoles);

  return (
    <motion.div
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      className="h-full flex flex-col relative"
    >
      {apiError && (
        <div className="mb-4 flex items-center gap-3 rounded-xl border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
          <AlertTriangle className="w-4 h-4 shrink-0" />
          <span className="flex-1">{apiError}</span>
          <button onClick={() => setApiError(null)} className="text-red-500 hover:text-red-700 font-medium">Dismiss</button>
        </div>
      )}

      {!isFormOpen ? (
        <>
          <div className="flex items-center justify-between mb-4">
            <div>
              <h1 className="text-3xl font-bold text-slate-800">User</h1>
              <p className="text-slate-500 mt-1"></p>
            </div>
            <div className="flex gap-3">
              <Button variant="filled" color="primary" icon={Plus} onClick={handleCreateNew}>
                Add User
              </Button>
            </div>
          </div>

          <div className="bg-white rounded-3xl shadow-sm border border-slate-100 flex-1 flex flex-col overflow-hidden">
            <div className="p-4 border-b border-slate-100 flex flex-wrap gap-4 items-center justify-between">
              <div className="relative flex-1 max-w-md">
                <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-slate-400" />
                <input
                  type="text"
                  placeholder="Search by ID, Name, or Username..."
                  value={searchTerm}
                  onChange={(e) => setSearchTerm(e.target.value)}
                  className="w-full pl-9 pr-4 py-2 bg-slate-50 border border-slate-200 rounded-lg focus:outline-none focus:ring-2 focus:ring-primary/20 focus:border-primary text-sm"
                />
              </div>
              <div className="flex items-center gap-2">
              <button onClick={() => setShowFilters(!showFilters)} title="Filters" className={showFilters ? "p-2 border rounded-lg transition-colors border-primary bg-primary/5 text-primary" : "p-2 border rounded-lg transition-colors border-slate-200 text-slate-500 hover:bg-slate-50"}>
                <Filter className="w-4 h-4" />
              </button>
              <button onClick={() => { setSearchTerm(''); setFilterDepartment(''); setFilterRole(''); }} title="Clear search & filters" className="p-2 border border-red-200 rounded-lg text-red-500 hover:bg-red-50 hover:border-red-300 transition-colors">
                <X className="w-4 h-4" />
              </button>
              <button onClick={() => exportToExcel(records, 'UsersMaster')} title="Export to Excel" className="p-2 border border-emerald-200 rounded-lg text-emerald-600 hover:bg-emerald-50 hover:border-emerald-300 transition-colors">
                <Download className="w-4 h-4" />
              </button>
            </div>
            </div>

            <AnimatePresence>
              {showFilters && (
                <motion.div
                  initial={{ height: 0, opacity: 0 }}
                  animate={{ height: 'auto', opacity: 1 }}
                  exit={{ height: 0, opacity: 0 }}
                  className="border-b border-slate-200 bg-slate-50/50 p-4"
                >
                  <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                    <select
                      value={filterRole}
                      onChange={(e) => setFilterRole(e.target.value)}
                      className="w-full px-3 py-2 bg-white border border-slate-200 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-primary/20"
                    >
                      <option value="">All Roles</option>
                      {paged.map(r => <option key={r} value={r}>{r}</option>)}
                    </select>
                    <select
                      value={filterDepartment}
                      onChange={(e) => setFilterDepartment(e.target.value)}
                      className="w-full px-3 py-2 bg-white border border-slate-200 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-primary/20"
                    >
                      <option value="">All Departments</option>
                      {allDepartments.map(d => <option key={d} value={d}>{d}</option>)}
                    </select>
                  </div>
                </motion.div>
              )}
            </AnimatePresence>

            <div className="flex-1 overflow-x-auto">
              <table className="w-full text-left text-sm">
                <thead className="bg-slate-50 border-b border-slate-200 text-slate-600">
                  <tr>
                    <th className="px-4 py-3 font-medium">User ID</th>
                    <th className="px-4 py-3 font-medium">Employee Name</th>
                    <th className="px-4 py-3 font-medium">Role</th>
                    <th className="px-4 py-3 font-medium">Department</th>
                    <th className="px-4 py-3 font-medium">Email</th>
                    <th className="px-4 py-3 font-medium text-center">Action</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {isLoading ? (
                    <tr><td colSpan={6} className="px-4 py-8 text-center text-slate-500">Loading users…</td></tr>
                  ) : filteredRecords.length > 0 ? (
                    pagedRecords.map((record) => (
                      <tr key={record.id} className="hover:bg-slate-50/50 transition-colors">
                        <td className="px-4 py-3 font-medium text-slate-800">{record.userId}</td>
                        <td className="px-4 py-3 font-medium text-primary">{record.employee}</td>
                        <td className="px-4 py-3 text-slate-600">{record.role}</td>
                        <td className="px-4 py-3 text-slate-600">{record.department}</td>
                        <td className="px-4 py-3 text-slate-600 truncate max-w-[150px]">{record.email}</td>
                        <td className="px-4 py-3 text-center">
                          <div className="flex items-center justify-center gap-2">
                            <button
                              onClick={() => handleEdit(record)}
                              className="p-1.5 text-slate-400 hover:text-primary hover:bg-primary/5 rounded-lg transition-colors"
                              title="Edit"
                            >
                              <Edit2 className="w-4 h-4" />
                            </button>
                            <button
                              onClick={() => handleDeleteRequest(record)}
                              className="p-1.5 text-red-500 hover:text-red-600 hover:bg-red-50 rounded-lg transition-colors"
                              title="Delete"
                            >
                              <Trash2 className="w-4 h-4" />
                            </button>
                          </div>
                        </td>
                      </tr>
                    ))
                  ) : (
                    <tr>
                      <td colSpan={6} className="px-4 py-8 text-center text-slate-500">
                        No users found matching your criteria.
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
        <Pagination page={page} pageSize={pageSize} totalItems={total} onPageChange={setPage} />
            <div className="flex flex-wrap items-center justify-between gap-3 p-4 border-t border-slate-100 text-sm text-slate-500">
              <div className="flex items-center gap-2">
                <span>Show</span>
                <select value={itemsPerPage} onChange={(e) => { setItemsPerPage(Number(e.target.value)); setCurrentPage(1); }} className="px-2 py-1 bg-white border border-slate-200 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-primary/20">
                  <option value={10}>10</option>
                  <option value={25}>25</option>
                  <option value={50}>50</option>
                  <option value={100}>100</option>
                </select>
                <span>entries</span>
                <span className="text-slate-400">· {filteredRecords.length} total</span>
              </div>
              <div className="flex items-center gap-3">
                <span>Page {_page} of {_totalPages}</span>
                <div className="flex gap-1">
                  <button onClick={() => setCurrentPage(p => Math.max(1, p - 1))} disabled={_page <= 1} className="px-3 py-1 border border-slate-200 rounded-lg hover:bg-slate-50 disabled:opacity-40 disabled:cursor-not-allowed">Prev</button>
                  <button onClick={() => setCurrentPage(p => Math.min(_totalPages, p + 1))} disabled={_page >= _totalPages} className="px-3 py-1 border border-slate-200 rounded-lg hover:bg-slate-50 disabled:opacity-40 disabled:cursor-not-allowed">Next</button>
                </div>
              </div>
            </div>
          </div>
        </>
      ) : (
        <>
          <div className="flex justify-between items-center mb-2">
            <div>
              <h1 className="text-2xl font-bold text-slate-800">
                {selectedRecord ? `Edit User: ${selectedRecord.employee}` : 'Add New User'}
              </h1>
            </div>
          </div>

          <div className="bg-white rounded-3xl shadow-sm border border-slate-100 flex-1 flex flex-col overflow-hidden">
            <div className="flex-1 overflow-y-auto p-6 space-y-4">

              {/* Employee Information */}
              <section>
                <h3 className="text-lg font-bold text-slate-800 mb-4 border-b border-slate-100 pb-2">Employee Information</h3>
                <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">User ID</label>
                    <input type="text" value={selectedRecord ? selectedRecord.userId : (nextCode || 'Auto-generated')} readOnly className="w-full px-4 py-2 bg-slate-100 border border-slate-200 rounded-xl text-sm text-slate-500 cursor-not-allowed focus:outline-none" />
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Employee Name <span className="text-red-500">*</span></label>
                    <input type="text" maxLength={LIMITS.employee} value={formData.employee} onChange={e => setFormData({...formData, employee: e.target.value})} className={`w-full px-4 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.employee ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                    {errors.employee && <p className="text-red-500 text-xs mt-1">{errors.employee}</p>}
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Username <span className="text-red-500">*</span></label>
                    <input type="text" maxLength={LIMITS.username} value={formData.username} onChange={e => setFormData({...formData, username: e.target.value})} className={`w-full px-4 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.username ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                    {errors.username && <p className="text-red-500 text-xs mt-1">{errors.username}</p>}
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Password {selectedRecord ? '' : <span className="text-red-500">*</span>}</label>
                    <div className="relative">
                      <input type={showPassword ? "text" : "password"} maxLength={LIMITS.passwordMax} value={formData.password} onChange={e => setFormData({...formData, password: e.target.value})} placeholder={selectedRecord ? "Leave blank to keep unchanged" : "Min 8 characters"} className={`w-full px-4 py-2 pr-10 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.password ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                      <button type="button" onClick={() => setShowPassword(!showPassword)} className="absolute right-3 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-600">
                        {showPassword ? <EyeOff className="w-4 h-4" /> : <Eye className="w-4 h-4" />}
                      </button>
                    </div>
                    {errors.password && <p className="text-red-500 text-xs mt-1">{errors.password}</p>}
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Confirm Password {selectedRecord ? '' : <span className="text-red-500">*</span>}</label>
                    <input type={showPassword ? "text" : "password"} maxLength={LIMITS.passwordMax} value={formData.confirmPassword} onChange={e => setFormData({...formData, confirmPassword: e.target.value})} className={`w-full px-4 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.confirmPassword ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                    {errors.confirmPassword && <p className="text-red-500 text-xs mt-1">{errors.confirmPassword}</p>}
                  </div>
                </div>
              </section>

              {/* Role Assignment */}
              <section>
                <h3 className="text-lg font-bold text-slate-800 mb-4 border-b border-slate-100 pb-2">Role &amp; Assignment</h3>
                <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Global Role <span className="text-red-500">*</span></label>
                    <select value={formData.role} onChange={e => setFormData({...formData, role: e.target.value})} className={`w-full px-4 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.role ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`}>
                      <option value="">Select Role</option>
                      {allRoles.map(r => <option key={r} value={r}>{r}</option>)}
                    </select>
                    {errors.role && <p className="text-red-500 text-xs mt-1">{errors.role}</p>}
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Department</label>
                    <select value={formData.department} onChange={e => setFormData({...formData, department: e.target.value})} className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-primary/20">
                      <option value="">None</option>
                      {allDepartments.map(d => <option key={d} value={d}>{d}</option>)}
                    </select>
                  </div>
                </div>

                {/* Permissions carried by the selected global role (read-only) */}
                {formData.role && (
                  <div className="mt-4 rounded-xl border border-slate-200 bg-slate-50/70 p-4">
                    <p className="text-xs font-semibold uppercase tracking-wide text-slate-500 mb-3">
                      Permissions granted by role “{formData.role}”
                    </p>
                    {selectedRolePerms ? (
                      <div className="flex flex-wrap gap-2">
                        <PermBadge on={selectedRolePerms.canCreateUsers} label="Create Users" />
                        <PermBadge on={selectedRolePerms.canAssignPermissions} label="Assign Permissions" />
                        {selectedRolePerms.defaultRole && (
                          <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-full text-xs font-medium bg-blue-50 text-blue-600 border border-blue-200">
                            Default Role
                          </span>
                        )}
                      </div>
                    ) : (
                      <p className="text-xs text-amber-600">
                        This role is no longer active in the Role Master — pick an active role or re-activate it.
                      </p>
                    )}
                  </div>
                )}
              </section>

              {/* Contact Information */}
              <section>
                <h3 className="text-lg font-bold text-slate-800 mb-4 border-b border-slate-100 pb-2">Contact Information</h3>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Email Address <span className="text-red-500">*</span></label>
                    <input type="email" maxLength={LIMITS.email} value={formData.email} onChange={e => setFormData({...formData, email: e.target.value})} className={`w-full px-4 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.email ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                    {errors.email && <p className="text-red-500 text-xs mt-1">{errors.email}</p>}
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Mobile Number</label>
                    <input type="text" maxLength={LIMITS.mobileNumber} value={formData.mobileNumber} onChange={e => setFormData({...formData, mobileNumber: e.target.value})} className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-primary/20" />
                  </div>
                </div>
              </section>

              {/* Security Settings */}
              <section>
                <h3 className="text-lg font-bold text-slate-800 mb-4 border-b border-slate-100 pb-2">Security Settings</h3>
                <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
                  <div className="flex items-center gap-3 mt-1 lg:mt-7">
                    <input type="checkbox" id="forcePassword" checked={formData.forcePasswordChange} onChange={e => setFormData({...formData, forcePasswordChange: e.target.checked})} className="w-4 h-4 text-primary bg-slate-100 border-slate-300 rounded focus:ring-primary" />
                    <label htmlFor="forcePassword" className="text-sm font-medium text-slate-700">Force Password Change</label>
                  </div>
                  <div className="flex items-center gap-3 mt-1 lg:mt-7">
                    <input type="checkbox" id="twoFactorAuth" checked={formData.twoFactorAuth} onChange={e => setFormData({...formData, twoFactorAuth: e.target.checked})} className="w-4 h-4 text-primary bg-slate-100 border-slate-300 rounded focus:ring-primary" />
                    <label htmlFor="twoFactorAuth" className="text-sm font-medium text-slate-700">Two-Factor Auth</label>
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Password Expiry (Days)</label>
                    <input type="number" min="0" max={LIMITS.expiryMax} value={formData.passwordExpiry} onChange={e => setFormData({...formData, passwordExpiry: e.target.value})} className={`w-full px-4 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 transition-all ${errors.passwordExpiry ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                    {errors.passwordExpiry && <p className="text-red-500 text-xs mt-1">{errors.passwordExpiry}</p>}
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Login Allowed Hours</label>
                    <div className="flex items-center gap-2">
                      <input type="time" value={formData.loginAllowedFrom} onChange={e => setFormData({...formData, loginAllowedFrom: e.target.value})} className="w-full px-2 py-2 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-primary/20" />
                      <span className="text-slate-400">to</span>
                      <input type="time" value={formData.loginAllowedTo} onChange={e => setFormData({...formData, loginAllowedTo: e.target.value})} className={`w-full px-2 py-2 bg-slate-50 border rounded-xl text-sm focus:outline-none focus:ring-2 ${errors.loginAllowedTo ? 'border-red-300 focus:ring-red-200' : 'border-slate-200 focus:ring-primary/20'}`} />
                    </div>
                    {errors.loginAllowedTo && <p className="text-red-500 text-xs mt-1">{errors.loginAllowedTo}</p>}
                  </div>
                </div>
              </section>

              {/* System Information */}
              <section>
                <h3 className="text-lg font-bold text-slate-800 mb-4 border-b border-slate-100 pb-2">System Information</h3>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                  <div>
                    <label className="block text-sm font-medium text-slate-700 mb-1">Remarks</label>
                    <input type="text" maxLength={LIMITS.remarks} value={formData.remarks} onChange={e => setFormData({...formData, remarks: e.target.value})} className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-primary/20" />
                  </div>
                </div>
              </section>

            </div>

            <div className="p-4 border-t border-slate-100 bg-slate-50/50 flex justify-between items-center shrink-0">
              <Button variant="outline" color="secondary" onClick={() => setFormData(emptyData)} icon={RefreshCw}>
                Reset
              </Button>
              <div className="flex gap-3">
                <Button variant="outline" color="secondary" onClick={() => { setIsFormOpen(false); setSelectedRecord(null); }}>
                  Cancel
                </Button>
                <Button variant="filled" color="primary" onClick={handleSaveForm} icon={Save} disabled={isSaving}>
                  {isSaving ? 'Saving…' : selectedRecord ? 'Update' : 'Save'}
                </Button>
              </div>
            </div>
          </div>
        </>
      )}

      <Modal
        isOpen={isDeleteOpen}
        onClose={() => setIsDeleteOpen(false)}
        title="Confirm Deletion"
        maxWidth="sm"
      >
        <div className="p-1">
          <div className="flex items-center gap-4 mb-6 text-amber-600 bg-amber-50 p-4 rounded-xl">
            <AlertTriangle className="w-8 h-8 shrink-0" />
            <p className="text-sm font-medium">
              Are you sure you want to delete User <strong>{selectedRecord?.employee}</strong>?
              This action cannot be undone.
            </p>
          </div>
          <div className="flex justify-end gap-3">
            <Button variant="outline" color="secondary" onClick={() => setIsDeleteOpen(false)}>
              Cancel
            </Button>
            <Button variant="filled" color="danger" onClick={confirmDelete}>
              Confirm Delete
            </Button>
          </div>
        </div>
      </Modal>
    </motion.div>
  );
};

// Read-only pill showing whether the selected role carries a given permission
