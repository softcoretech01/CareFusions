from pydantic import BaseModel, Field, field_validator
from typing import Optional
from datetime import datetime
from enum import Enum


class StatusEnum(str, Enum):
    Active   = "Active"
    Inactive = "Inactive"


# ── Field limits (kept in sync with the frontend LIMITS + DB columns) ──
NAME_MAX    = 100
DESC_MAX    = 500
REMARKS_MAX = 500


# ── Shared field rules ───────────────────────────────────────
class _PaymentModeFields(BaseModel):
    paymentMode:         str            = Field(max_length=NAME_MAX)
    description:         Optional[str]  = Field(default=None, max_length=DESC_MAX)
    transactionRequired: bool          = False
    supportsRefund:      bool          = False
    isDefault:           bool          = False
    status:              StatusEnum     = StatusEnum.Active
    remarks:             Optional[str]  = Field(default=None, max_length=REMARKS_MAX)

    @field_validator("paymentMode")
    @classmethod
    def not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Payment Mode is required and cannot be blank")
        return v.strip()

    @field_validator("description", "remarks")
    @classmethod
    def blank_to_none(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return None
        v = v.strip()
        return v or None


# ── Request: Create (code auto-generated by SP) ──────────────
class PaymentModeCreate(_PaymentModeFields):
    createdBy: Optional[str] = None


# ── Request: Update (PaymentCode is immutable) ───────────────
class PaymentModeUpdate(_PaymentModeFields):
    updatedBy: Optional[str] = None


# ── Response ─────────────────────────────────────────────────
class PaymentModeResponse(BaseModel):
    id:                  int
    paymentCode:         str
    paymentMode:         str
    description:         Optional[str]
    transactionRequired: bool
    supportsRefund:      bool
    isDefault:           bool
    status:              str
    remarks:             Optional[str]
    createdBy:           Optional[str]
    createdDate:         Optional[datetime]
    updatedBy:           Optional[str]
    updatedDate:         Optional[datetime]

    class Config:
        from_attributes = True
